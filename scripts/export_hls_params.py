#!/usr/bin/env python3
"""Export trained Transformer weights to a Vitis HLS header."""

from __future__ import annotations

import argparse
from pathlib import Path

import torch


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_LOG_ROOT = PROJECT_ROOT / "notebooks" / "lightning_logs"
DEFAULT_OUTPUT = PROJECT_ROOT / "vitis_hls" / "transformer" / "scaled_dp_params.h"

REQUIRED_TRANSFORMER_KEYS = (
    "front_linear.weight",
    "front_linear.bias",
    "transformer_encoder.layers.0.self_attn.query_mat.weight",
    "transformer_encoder.layers.0.self_attn.key_mat.weight",
    "transformer_encoder.layers.0.self_attn.value_mat.weight",
    "transformer_encoder.layers.0.self_attn.o_proj.weight",
    "transformer_encoder.layers.0.self_attn.o_proj.bias",
    "transformer_encoder.layers.0.linear_net.0.weight",
    "transformer_encoder.layers.0.linear_net.0.bias",
    "transformer_encoder.layers.0.linear_net.3.weight",
    "transformer_encoder.layers.0.linear_net.3.bias",
    "final_linear.weight",
    "final_linear.bias",
)


def checkpoint_model_type(checkpoint_path: Path) -> str | None:
    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    state_dict = checkpoint.get("state_dict", {})
    if not all(key in state_dict for key in REQUIRED_TRANSFORMER_KEYS):
        return None

    block_args = checkpoint.get("hyper_parameters", {}).get("block_args", {})
    if "num_heads" in block_args:
        return "transformer"
    return "linear_transformer"


def checkpoint_is_transformer(checkpoint_path: Path) -> bool:
    return checkpoint_model_type(checkpoint_path) in {"transformer", "linear_transformer"}


def find_latest_checkpoint(log_root: Path, model_type: str) -> Path:
    candidates = sorted(
        log_root.glob("version_*/checkpoints/*.ckpt"),
        key=lambda path: path.stat().st_mtime,
        reverse=True,
    )
    for checkpoint_path in candidates:
        if checkpoint_model_type(checkpoint_path) == model_type:
            return checkpoint_path
    raise FileNotFoundError(f"No compatible {model_type} checkpoint found under {log_root}")


def find_latest_transformer_checkpoint(log_root: Path) -> Path:
    return find_latest_checkpoint(log_root, "transformer")


def c_identifier(name: str) -> str:
    return name.upper().replace(".", "_")


def format_tensor(name: str, tensor: torch.Tensor) -> str:
    tensor = tensor.detach().cpu().float()
    if tensor.ndim == 2:
        # PyTorch Linear stores weights as (out_features, in_features), while
        # the HLS matrix multiplier expects (in_features, out_features).
        tensor = tensor.T.contiguous()
        shape = "".join(f"[{dim}]" for dim in tensor.shape)
        rows = []
        for row in tensor:
            rows.append("{" + ", ".join(f"{x:.6f}f" for x in row.tolist()) + "}")
        values = "{\n    " + ",\n    ".join(rows) + "\n}"
    elif tensor.ndim == 1:
        shape = f"[{tensor.shape[0]}]"
        values = "{" + ", ".join(f"{x:.6f}f" for x in tensor.tolist()) + "}"
    else:
        raise ValueError(f"Unsupported tensor shape for {name}: {tuple(tensor.shape)}")

    return f"static const float {c_identifier(name)}{shape} = {values};"


def export_header(checkpoint_path: Path, output_path: Path) -> None:
    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    state_dict = checkpoint["state_dict"]
    missing = [key for key in REQUIRED_TRANSFORMER_KEYS if key not in state_dict]
    if missing:
        raise KeyError(f"Checkpoint is missing Transformer parameters: {missing}")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/export_hls_params.py",
        f"// Source checkpoint: {checkpoint_path.relative_to(PROJECT_ROOT)}",
        "",
    ]
    for key in REQUIRED_TRANSFORMER_KEYS:
        lines.append(format_tensor(key, state_dict[key]))
        lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--checkpoint",
        type=Path,
        default=None,
        help="Lightning checkpoint to export. Defaults to the latest compatible Transformer checkpoint.",
    )
    parser.add_argument(
        "--model-type",
        choices=["transformer", "linear_transformer"],
        default="transformer",
        help="Model family to use when --checkpoint is not provided.",
    )
    parser.add_argument(
        "--log-root",
        type=Path,
        default=DEFAULT_LOG_ROOT,
        help="Lightning log root used when --checkpoint is not provided.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Output scaled_dp_params.h path.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    checkpoint_path = args.checkpoint or find_latest_checkpoint(args.log_root, args.model_type)
    checkpoint_path = checkpoint_path.resolve()
    output_path = args.output.resolve()
    export_header(checkpoint_path, output_path)
    print(f"Exported {checkpoint_path.relative_to(PROJECT_ROOT)}")
    print(f"Wrote {output_path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
