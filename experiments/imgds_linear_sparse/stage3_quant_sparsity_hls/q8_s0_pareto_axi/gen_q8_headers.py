#!/usr/bin/env python3
"""Generate Q8 (ap_fixed<8,4>) HLS headers from trained checkpoint."""
import sys, os, numpy as np
PROJ = '/home/cym/prj2/finn/notebooks/icl_thesis-master'
EXP  = f'{PROJ}/experiments/imgds_linear_sparse'
STG3 = f'{EXP}/stage3_quant_sparsity_hls/q8_s0_pareto_axi'
sys.path.insert(0, f'{PROJ}/src')
import torch, torch.nn as nn
from collections import OrderedDict
from src.transformer import LinearUNSWAnomalyDetector

D_MODEL, SEQ_LEN, INPUT_DIM, FF_DIM, N_CLASSES = 16, 16, 64, 32, 2
MC = {'input_dim':INPUT_DIM,'seq_len':SEQ_LEN,'d_model':D_MODEL,'dim_feedforward':FF_DIM,'num_layers':1,'num_classes':N_CLASSES,'dropout':0.0}

class W(nn.Module):
    def __init__(self):
        super().__init__()
        self.backbone = LinearUNSWAnomalyDetector(**MC)
    def forward(self, x): return self.backbone(x)

# Load checkpoint
ckpt = torch.load(f'{EXP}/checkpoints/best_linear_imgds_dense_r32_p8.pt', map_location='cpu', weights_only=False)
sd = ckpt.get('model_state_dict', ckpt.get('state_dict', ckpt))
if any(k.startswith('backbone.') for k in sd.keys()):
    sd = OrderedDict((k.replace('backbone.',''), v.clone()) for k,v in sd.items())
sd = OrderedDict((k,v) for k,v in sd.items() if isinstance(v, torch.Tensor))
print(f'Loaded {len(sd)} tensors from checkpoint')

# Q8 quantize: ap_fixed<8,4> -> 8 bits total, 4 int bits, 4 frac bits
def q8_quant(w):
    s = 2**4; mx = 2**3 - 2**(-4); mn = -2**3
    return torch.clamp(torch.round(w * s), mn * s, mx * s) / s

q8_sd = OrderedDict()
clamped = 0
for k, v in sd.items():
    iw = 'weight' in k and v.ndim >= 2
    inn = 'norm' in k.lower()
    if iw and not inn:
        qv = q8_quant(v)
        q8_sd[k] = qv
        if (qv.abs() >= 7.9).any(): clamped += 1
    else:
        q8_sd[k] = v.clone()
print(f'Q8 quantized. Clamped weights: {clamped} tensors')

def fmt_arr(arr, indent=4):
    sp = ' '*indent; lines = []
    for i in range(0, len(arr), 8):
        vals = ', '.join(f'{x: .7f}f' for x in arr[i:i+8])
        lines.append(f'{sp}{vals}{"," if i+8 < len(arr) else ""}')
    return '\n'.join(lines)

param_map = [
    ('classifier.bias', 'classifier_bias', [2]),
    ('classifier.weight', 'classifier_weight', [2, 16]),
    ('input_projection.bias', 'input_projection_bias', [16]),
    ('input_projection.weight', 'input_projection_weight', [16, 64]),
    ('position_embedding', 'position_embedding', [1, 16, 16]),
    ('layers.0.attention.query.weight', 'layers_0_attention_query_weight', [16, 16]),
    ('layers.0.attention.key.weight', 'layers_0_attention_key_weight', [16, 16]),
    ('layers.0.attention.value.weight', 'layers_0_attention_value_weight', [16, 16]),
    ('layers.0.attention.output.weight', 'layers_0_attention_output_weight', [16, 16]),
    ('layers.0.attention.output.bias', 'layers_0_attention_output_bias', [16]),
    ('layers.0.norm1.weight', 'layers_0_norm1_weight', [16]),
    ('layers.0.norm1.bias', 'layers_0_norm1_bias', [16]),
    ('layers.0.feedforward.0.weight', 'layers_0_feedforward_0_weight', [32, 16]),
    ('layers.0.feedforward.0.bias', 'layers_0_feedforward_0_bias', [32]),
    ('layers.0.feedforward.3.weight', 'layers_0_feedforward_3_weight', [16, 32]),
    ('layers.0.feedforward.3.bias', 'layers_0_feedforward_3_bias', [16]),
    ('layers.0.norm2.weight', 'layers_0_norm2_weight', [16]),
    ('layers.0.norm2.bias', 'layers_0_norm2_bias', [16]),
    ('output_norm.weight', 'output_norm_weight', [16]),
    ('output_norm.bias', 'output_norm_bias', [16]),
]

hdr = ['// Auto-generated Q8-S0 (ap_fixed<8,4>) HLS parameters',
       '// Generated by gen_q8_headers.py',
       '#ifndef HLS_PARAMS_Q8_H', '#define HLS_PARAMS_Q8_H', '',
       '#include <ap_fixed.h>', '',
       '#define SEQ_LEN   16', '#define INPUT_DIM 64', '#define D_MODEL   16',
       '#define FF_DIM    32', '#define N_CLASSES 2', '#define N_EVAL    200', '']

for pt_name, c_name, shape in param_map:
    found = None
    search = pt_name.split('.')[-1]
    for k, v in q8_sd.items():
        if k.endswith(search):
            found = v; break
    if found is None:
        print(f'WARNING: {pt_name} not found'); continue
    flat = found.numpy().flatten()
    hdr.append(f'// {pt_name}  shape={list(found.shape)}')
    hdr.append(f'static const ap_fixed<8,4> {c_name}[{len(flat)}] = {{')
    hdr.append(fmt_arr(flat)); hdr.append('};'); hdr.append('')
hdr.append('#endif\n')

params_path = f'{STG3}/hls/src/hls_params_q8.h'
os.makedirs(os.path.dirname(params_path), exist_ok=True)
with open(params_path, 'w') as f: f.write('\n'.join(hdr))
print(f'Written: {params_path} ({len(hdr)} lines)')

# ---- Eval samples with Q8 ref logits ----
model_q8 = W(); model_q8.backbone.load_state_dict(q8_sd, strict=True); model_q8.eval()
eval_npz = np.load(f'{EXP}/outputs/imgds_r32_p8_fpga_eval_200.npz')
X_eval = eval_npz['X']; y_eval = eval_npz['y']

with torch.no_grad():
    ref_logits = model_q8(torch.from_numpy(X_eval).float()).numpy()

esh = ['// Auto-generated Q8 evaluation samples (200 samples)',
       '#ifndef EVAL_SAMPLES_Q8_H', '#define EVAL_SAMPLES_Q8_H', '',
       '#include <ap_fixed.h>', '',
       '#define N_EVAL_SAMPLES 200', '#define SEQ_LEN       16',
       '#define INPUT_DIM     64', '#define N_CLASSES      2', '']
flat_in = X_eval.flatten()
esh.append(f'static const float eval_inputs_flat[{len(flat_in)}] = {{')
esh.append(fmt_arr(flat_in)); esh.append('};'); esh.append('')
esh.append('// Q8 reference logits (from Q8-quantized model)')
esh.append('static const float ref_logits[200][2] = {')
for n in range(200):
    vals = f'{ref_logits[n,0]: .7f}f, {ref_logits[n,1]: .7f}f'
    esh.append(f'    {{{vals}}}{"," if n < 199 else ""}')
esh.append('};'); esh.append('')
labels_str = ', '.join(str(int(y)) for y in y_eval)
esh.append(f'static const int eval_labels[200] = {{{labels_str}}};')
esh.append(''); esh.append('#endif')

eval_path = f'{STG3}/hls/src/eval_samples_q8.h'
with open(eval_path, 'w') as f: f.write('\n'.join(esh))
print(f'Written: {eval_path} ({len(esh)} lines)')
print('\nDone.')
