def ap_fixed_str(val, n=16, m=6):
    """Convert float to C++ ap_fixed<16,6> literal."""
    # ap_fixed: Q6.10 format → multiply by 2^6=64
    # Actually the HLS uses float literals and ap_fixed conversion
    return f"{val:.8f}f"

def write_1d_weight_array(out, name, data, dtype="float"):
    """Write 1D const array in C++."""
    out.write(f"static const ap_fixed<16,6> {name}[{len(data)}] = {{\n")
    for i in range(0, len(data), 8):
        vals = ", ".join(ap_fixed_str(v) for v in data[i:i+8].flat)
        out.write(f"    {vals},\n")
    out.write("};\n\n")

def write_2d_weight_array(out, name, data):
    """Write flat 2D const array in C++."""
    flat = data.flatten()
    write_1d_weight_array(out, name, flat)

def float_to_q16(val):
    """Convert float to Q6.10 fixed-point string for ap_fixed<16,6>."""
    return f"{val:.6f}f"

def write_weight_table(out, name, data_2d, rows, cols):
    """Write a flattened row-major weight table."""
    flat = data_2d.reshape(-1)
    out.write(f"// {name}  shape=[{rows}, {cols}]\n")
    out.write(f"static const data_t {name}[{rows * cols}] = {{\n")
    line = []
    for i, v in enumerate(flat):
        line.append(f"{float(v):.8f}f")
        if len(line) == 8 or i == len(flat) - 1:
            out.write("    " + ", ".join(line) + ",\n")
            line = []
    out.write("};\n\n")

